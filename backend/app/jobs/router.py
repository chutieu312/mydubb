FIXTURE_NOTICE = (
    "The audio is a fixed development fixture. It was NOT generated from your transcript "
    "and does NOT match the target duration."
)
# {language} is the job's own output language (`TargetLanguage.noun`): "Vietnamese" gives the
# notices worded exactly as before the option existed.
ILLUSTRATIVE_NOTICE = "The {language} text is illustrative mock content, not a real translation."
SPEECH_NOTICE = (
    "Speech was generated by Azure Speech from the {language} text above. English technical "
    "terms from the MyDubb glossary are read as English by the same voice; an English term that "
    "is not in the glossary is read as part of the {language} text and can sound wrong."
)
DURATION_NOTICE = (
    "The audio length has not been adjusted to the target duration yet, so it can be longer "
    "or shorter than the target."
)
DURATION_ADJUSTED_NOTICE = (
    "The audio was sped up or slowed down as a whole (pitch preserved) so that it lasts exactly "
    "the target duration. Nothing was cut or repeated; the measured durations are listed below."
)
SPEED_NOTICE = (
    "Audio speed {speed}: the audio is the baseline duration (last - first sentence start) "
    "divided by {speed}, so it is {relation} the video's time span between those two timestamps."
)
SPEED_NOT_APPLIED_NOTICE = (
    "Audio speed {speed} was selected, but this audio processor does not adjust duration, so "
    "the audio is neither the baseline length nor the length that speed would give."
)
TIMED_NOTICE = (
    "Timed transcript: the speech follows the caption times. Times inside a caption are "
    "estimated from word counts, and neighbouring sentences can share one stretch of time, so "
    "some sentences start a little before or after their caption. This is not exact "
    "sentence-by-sentence synchronization."
)
TIMED_ADJUSTED_NOTICE = (
    "Each stretch of time holds its sentences: speech that was too long was sped up (pitch "
    "preserved) only as much as that stretch needed, and shorter speech is followed by silence. "
    "Nothing was cut or repeated, and the whole audio lasts exactly the target duration."
)
TIMED_FAST_NOTICE = (
    "{count} stretch(es) still needed more than {level:g}x tempo after grouping, so speech can "
    "sound fast there."
)
GLOSSARY_NOTICE = (
    "Translated by Azure Translator. Technical terms from the MyDubb glossary are kept in "
    "English; terms that are not in the glossary may be translated."
)


@router.post("", status_code=status.HTTP_202_ACCEPTED, response_model=JobResponse)
def create_job(
    body: CreateJobRequest,
    request: Request,
    response: Response,
    principal: Principal = Depends(require_job_access_csrf),
    db: Session = Depends(get_db),
    services: AppServices = Depends(get_services),
) -> JobResponse:
    if body.timing_mode is TimingMode.TIMED and not services.pipeline.timed_mode_available():
        # Refused before any slot, job row or provider call: there is no partial result to undo.
        raise ApiError(
            status.HTTP_409_CONFLICT,
            "timing_mode_unavailable",
            "Timed transcripts need the server's audio processing, which is not enabled on this "
            "server. Process the transcript as plain text (tick 'Ignore the timestamps').",
        )
    guest = services.guest
    ip_key: str | None = None
    if principal.guest:
        # Checked before any slot or row: a refused guest request uses up nothing.
        assert guest is not None  # a guest principal exists only with guest access on
        _check_guest_words(body, guest)
        _check_guest_duration(body, guest)
        ip_key = guest.network_key(request)
        if ip_key is None:
            raise network_unknown()
    try:
        slot = services.executor.reserve()
    except ExecutorAtCapacity:
        raise ApiError(
            status.HTTP_503_SERVICE_UNAVAILABLE,
            "server_at_capacity",
            "The server is already processing the maximum number of jobs it can handle. "
            "Please try again when a running job finishes.",
            headers={"Retry-After": "30"},
        ) from None

    def new_job() -> Job:
        return service.create_job(
            db,
            # The owner comes from the session, never from the request body.
            session_id=None if principal.user or principal.guest else principal.session_id,
            user_id=principal.user_id,
            guest_session_id=principal.guest_session_id,
            voice=body.voice.value,
            target_language=body.target_language,
            first_sentence_start_seconds=parse_timestamp(body.first_sentence_start),
            last_sentence_start_seconds=parse_timestamp(body.last_sentence_start),
            audio_speed=body.speed,
            transcript_char_count=len(body.spoken_text),
            **services.pipeline.provider_names(),
            runner_id=services.instance_id,
        )

    try:
        if principal.guest:
            assert guest is not None and principal.guest_session_id is not None
            assert ip_key is not None
            # The job row and its quota place are written together, under the quota locks.
            job = reserve_job(
                db,
                guest_session_id=principal.guest_session_id,
                ip_key=ip_key,
                policy=guest.policy,
                create_job=new_job,
            )
        else:
            job = new_job()
        # Commit before starting so the worker always sees the queued row.
        db.commit()
    except GuestQuotaExceeded as exc:
        slot.cancel()
        assert guest is not None
        raise _quota_error(exc, guest) from None
    except GuestSessionGone:
        slot.cancel()
        raise not_authenticated() from None
    except Exception:
        slot.cancel()
        raise

    job_input = JobInput(
        job_id=job.id,
        transcript=body.spoken_text,
        voice=body.voice,
        target_language=body.target_language,
        baseline_seconds=job.target_duration_seconds,
        speed=body.speed,
        timed=body.timed,
        usage_context=_usage_context(principal),
    )
    services.pipeline.start(slot, job_input)
    response.headers["Location"] = f"/api/jobs/{job.id}"
    return JobResponse.from_job(job)


def _usage_context(principal: Principal) -> UsageContext:
    """Fixed labels for the usage record; no identity leaves this function."""
    if principal.guest:
        access = "guest"
    elif principal.user is not None:
        access = "invitation"
    else:
        access = "access_code"
    return UsageContext(client="extension" if principal.bearer else "web", access=access)


def _check_guest_words(body: CreateJobRequest, guest: GuestAccess) -> None:
    """The guest word limit, on the text that would be translated (no timestamps or markup)."""
    words = count_words(body.spoken_text)
    limit = guest.policy.max_words
    if words > limit:
        message = (
            f"Guest jobs can have at most {limit:,} words; this transcript has {words:,} "
            "(timestamps not counted). Shorten it, or sign in with your invitation."
        )
        raise ApiError(
            status.HTTP_422_UNPROCESSABLE_CONTENT,
            "guest_word_limit_exceeded",
            message,
            extra={
                "fields": [{"field": "transcript", "message": message}],
                "word_count": words,
                "max_words": limit,
            },
        )


def _check_guest_duration(body: CreateJobRequest, guest: GuestAccess) -> None:
    """The guest audio length limit, on the output length the job would produce (baseline /
    speed, the same calculation as the audio target). The timestamps are never adjusted."""
    baseline = target_duration_seconds(
        parse_timestamp(body.first_sentence_start), parse_timestamp(body.last_sentence_start)
    )
    output = DurationTarget(baseline, body.speed).output_seconds
    limit = guest.policy.max_output_seconds
    if output <= limit:
        return
    message = (
        f"Guest audio can be at most {_clock(limit)} long; this job would make "
        f"{_clock(output)} ({_clock(baseline)} between the two start times at "
        f"{body.speed.label}). Choose a shorter stretch or a faster speed, or sign in with "
        "your invitation."
    )
    raise ApiError(
        status.HTTP_422_UNPROCESSABLE_CONTENT,
        "guest_duration_limit_exceeded",
        message,
        extra={
            "fields": [{"field": "last_sentence_start", "message": message}],
            "output_seconds": float(output),
            "max_output_seconds": limit,
            "baseline_seconds": baseline,
            "speed": body.speed.number,
        },
    )


def _clock(seconds: int | Fraction) -> str:
    """12:30 or 1:02:03 (seconds rounded up, so a length just over a limit never reads as it)."""
    whole = math.ceil(seconds)
    hours, rest = divmod(whole, 3600)
    minutes, secs = divmod(rest, 60)
    return f"{hours}:{minutes:02d}:{secs:02d}" if hours else f"{minutes}:{secs:02d}"


def _quota_error(exc: GuestQuotaExceeded, guest: GuestAccess) -> ApiError:
    policy = guest.policy
    running = (
        f" ({exc.in_flight} still processing; a job that fails gives its place back)"
        if exc.in_flight
        else ""
    )
    if exc.scope == "session":
        return ApiError(
            status.HTTP_429_TOO_MANY_REQUESTS,
            "guest_session_quota_exhausted",
            f"This guest session has used all {policy.jobs_per_session} of its jobs{running}. "
            "Sign in with your invitation to keep dubbing.",
            extra={"limit": policy.jobs_per_session},
        )
    hours = policy.ip_window_seconds / 3600
    headers = {"Retry-After": str(exc.retry_after)} if exc.retry_after else None
    extra: dict = {"limit": policy.jobs_per_ip, "window_seconds": policy.ip_window_seconds}
    if exc.retry_after:
        extra["retry_after_seconds"] = exc.retry_after
    return ApiError(
        status.HTTP_429_TOO_MANY_REQUESTS,
        "guest_ip_quota_exhausted",
        f"Guests on your network have used all {policy.jobs_per_ip} guest jobs allowed in "
        f"{hours:g} hours{running}. Everyone on the same network shares this limit. Try again "
        "later, or sign in with your invitation.",
        headers=headers,
        extra=extra,
    )


def _owned_job_or_404(db: Session, job_id: uuid.UUID, principal: Principal) -> Job:
    job = service.get_owned_job(
        db,
        job_id,
        session_id=None if principal.guest else principal.session_id,
        user_id=principal.user_id,
        guest_session_id=principal.guest_session_id,
    )
    if job is None:
        raise ApiError(status.HTTP_404_NOT_FOUND, "job_not_found", "Job not found.")
    return job


def _available_result(job: Job, services: AppServices) -> StoredResult:
    if job.status == JobStatus.FAILED:
        raise ApiError(
            status.HTTP_409_CONFLICT,
            "job_failed",
            job.error_message or "The job failed.",
            extra={"job_error_code": job.error_code},
        )
    if job.status != JobStatus.COMPLETED:
        raise ApiError(
            status.HTTP_409_CONFLICT, "result_not_ready", "The job has not completed yet."
        )
    stored = services.result_store.get(job.id)
    if stored is None:
        raise ApiError(
            status.HTTP_410_GONE,
            "result_expired",
            "The temporary result has expired or was removed from the server. "
            "Results are not stored permanently; please generate the dubbing again.",
        )
    return stored


@router.get("/{job_id}", response_model=JobResponse)
def get_job(
    job_id: uuid.UUID,
    principal: Principal = Depends(require_job_access),
    db: Session = Depends(get_db),
) -> JobResponse:
    return JobResponse.from_job(_owned_job_or_404(db, job_id, principal))


@router.get("/{job_id}/result", response_model=JobResultResponse)
def get_result(
    job_id: uuid.UUID,
    principal: Principal = Depends(require_job_access),
    db: Session = Depends(get_db),
    services: AppServices = Depends(get_services),
) -> JobResultResponse:
    job = _owned_job_or_404(db, job_id, principal)
    stored = _available_result(job, services)
    speed = AudioSpeed(job.audio_speed_percent)
    # The job's own language, stored at submission; never the form's or the server's.
    language = TargetLanguage(job.target_language)
    timing = TimingOut.from_summary(stored.timing) if stored.timing else None
    notices = []
    if stored.translation_is_illustrative:
        notices.append(ILLUSTRATIVE_NOTICE.format(language=language.noun))
    else:
        notices.append(GLOSSARY_NOTICE)
    if stored.audio_is_fixture:
        notices.append(FIXTURE_NOTICE)
    else:
        notices.append(SPEECH_NOTICE.format(language=language.noun))
        if not stored.duration_adjusted:
            notices.append(DURATION_NOTICE)
        elif timing is None:
            notices.append(DURATION_ADJUSTED_NOTICE)
        else:
            notices.append(TIMED_ADJUSTED_NOTICE)
    if timing is not None:
        notices.append(TIMED_NOTICE)
        if timing.frames_over_warning_level:
            notices.append(
                TIMED_FAST_NOTICE.format(
                    count=timing.frames_over_warning_level, level=timing.tempo_warning_level
                )
            )
    if speed is not AudioSpeed.X1:
        if stored.duration_adjusted:
            relation = "shorter than" if speed.value > 100 else "longer than"
            notices.append(SPEED_NOTICE.format(speed=speed.label, relation=relation))
        else:
            notices.append(SPEED_NOT_APPLIED_NOTICE.format(speed=speed.label))
    audio_url = f"/api/jobs/{job.id}/result/audio"
    return JobResultResponse(
        job_id=job.id,
        target_language=language.value,
        target_language_label=language.label,
        baseline_duration_seconds=job.target_duration_seconds,
        speed=speed.number,
        output_duration_seconds=float(
            DurationTarget(job.target_duration_seconds, speed).output_seconds
        ),
        translation=TranslationOut(
            text=stored.translation_text,
            is_illustrative=stored.translation_is_illustrative,
            provider=job.translation_provider,
        ),
        audio=AudioOut(
            url=audio_url,
            download_url=f"{audio_url}?download=1",
            content_type="audio/mpeg",
            provider=job.speech_provider,
            is_fixture=stored.audio_is_fixture,
            duration_adjusted=stored.duration_adjusted,
            duration=(DurationOut(**stored.duration_report) if stored.duration_report else None),
        ),
        expires_at=stored.expires_at,
        notices=notices,
        timing=timing,
    )


@router.get("/{job_id}/result/audio")
def get_result_audio(
    job_id: uuid.UUID,
    download: bool = False,
    principal: Principal = Depends(require_job_access),
    db: Session = Depends(get_db),
    services: AppServices = Depends(get_services),
) -> FileResponse:
    job = _owned_job_or_404(db, job_id, principal)
    stored = _available_result(job, services)
    return FileResponse(
        stored.audio_path,
        media_type="audio/mpeg",
        filename=f"mydubb-{job.id}.mp3",
        content_disposition_type="attachment" if download else "inline",
        headers={"Cache-Control": "private, no-store"},
    )
